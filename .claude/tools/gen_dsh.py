def find_row(rows: Any, row_id: str, name: str, what: str, hint: str) -> Any:
  row = next((r for r in rows if isinstance(r, dict) and r.get("id") == row_id), None)
  if row is None or row.get("name") != name:
    raise GeneratorError(f"{what} has no row '{row_id}' ({name}); {hint}")
  return row


def locate(preset: Any, what: str, hint: str) -> tuple[Any, Any]:
  """The skill-filesystem row and the delegation group of a preset entry."""
  config = preset.get("config") if isinstance(preset, dict) else None
  plugins = config.get("plugins") if isinstance(config, dict) else None
  if not isinstance(plugins, list):
    raise GeneratorError(f"{what} has no config.plugins list; {hint}")
  skills = find_row(plugins, "skill-filesystem", "@deepseek-ai/dsh-skill-filesystem", what, hint)
  group = find_row(plugins, "delegation", "cordis:group", what, hint)
  if group.get("group") is not True or not isinstance(group.get("config"), list):
    raise GeneratorError(f"{what}: row 'delegation' is not a group; {hint}")
  return skills, group


def load_shipped_preset(asar: Path) -> Any:
  text = read_asar(asar, PRESET_PATH).decode("utf-8")
  rows = [
    row for e in load(text, "shipped standard preset") if isinstance(e, dict)
    for row in e.get("insert") or []
  ]
  row = next((r for r in rows if isinstance(r, dict) and r.get("id") == PRESET_ROW_ID), None)
  config = row.get("config") if row else None
  if (row is None or row.get("name") != PRESET_ROW_NAME or not isinstance(config, dict)
      or config.get("id") != "standard" or not isinstance(config.get("plugins"), list)):
    raise GeneratorError(f"shipped standard preset: row '{PRESET_ROW_ID}' is missing or changed")
  return row


def load_other_presets(asar: Path) -> tuple[list[Any], bool, list[Any]]:
  """Read every Web bundle preset and the effective shared working-directory switch."""
  try:
    metadata = json.loads(read_asar(asar, WEB_PACKAGE_PATH))
    patches = metadata["dsh"]["bundle"]["patch"]
  except (ValueError, KeyError, TypeError):
    raise GeneratorError("Web bundle patch list is missing or changed") from None
  if not isinstance(patches, list) or not all(isinstance(p, str) and p.startswith("./") and ".." not in p for p in patches):
    raise GeneratorError("Web bundle patch list has unsupported paths")
  base = load(read_asar(asar, BASE_PATCH_PATH).decode("utf-8"), "shipped base patch")
  root_rows = [r for e in base for r in e.get("insert", [e])]
  workdir = next((r for r in root_rows if r.get("id") == WORKING_DIRECTORY_ROW), None)
  if workdir is None or workdir.get("name") != WORKING_DIRECTORY_PLUGIN or workdir.get("disabled", False) not in (True, False):
    raise GeneratorError("shipped working-directory tool is missing or changed")
  enabled = workdir.get("disabled") is not True
  presets: list[Any] = []
  patches_to_apply = list(base)
  for relative in patches:
    inner = str(Path(WEB_PACKAGE_PATH).parent / relative[2:])
    entries = load(read_asar(asar, inner).decode("utf-8"), "shipped Web bundle patch")
    patches_to_apply.extend(entries)
    for entry in entries:
      for row in entry.get("insert", [entry]):
        if row.get("name") == PRESET_ROW_NAME and row.get("id") != PRESET_ROW_ID:
          presets.append(row)
        if row.get("id") == WORKING_DIRECTORY_ROW and "disabled" in row:
          if row["disabled"] not in (True, False):
            raise GeneratorError("shipped working-directory tool has a conditional switch")
          enabled = not row["disabled"]
  return presets, enabled, effective_global_entries(patches_to_apply)


def preserve_working_directory(
  data: Sequence[Any], chunks: list[str], inputs: Inputs, standard: Any
) -> list[tuple[int | None, Any, Any]]:
  """Move the inherited tool into all non-role presets, keeping their effective child lists."""
  enabled = inputs.global_working_directory
  migration = False
  for i, entry in enumerate(data):
    if "insert" in entry and entry.get("id"):
      continue  # Такая запись добавляет строки в группу, а не в корень.
    for row in entry.get("insert", [entry]):
      if row.get("name") == WORKING_DIRECTORY_PLUGIN and row.get("id") != WORKING_DIRECTORY_ROW:
        raise GeneratorError("another global working-directory tool would be inherited; move it into a non-role preset")
      if row.get("id") == WORKING_DIRECTORY_ROW:
        if set(row) - {"id", "name", "disabled"} or row.get("name", WORKING_DIRECTORY_PLUGIN) != WORKING_DIRECTORY_PLUGIN:
          raise GeneratorError("global working-directory row has unsupported edits; nothing written")
        if "disabled" in row:
          if row["disabled"] not in (True, False):
            raise GeneratorError("global working-directory row has a conditional switch; nothing written")
          enabled = not row["disabled"]
        migration = _MARKER_COMMENT.search(chunks[i].splitlines()[0]) is not None and row.get("disabled") is True
  if not enabled and not migration:
    return []
  effective = effective_global_entries(data, inputs.global_entries)
  if any(row.get("name") == PRESET_ROW_NAME and depth > 0 for row, depth in active_global_rows(effective)):
    raise GeneratorError("active nested Agent Preset prevents safe working-directory migration; nothing written")

  def add_tool(preset: Any) -> None:
    config = preset.get("config")
    plugins = config.get("plugins") if isinstance(config, dict) else None
    if not isinstance(plugins, list):
      raise GeneratorError("non-role preset has no plugin list; cannot preserve working-directory access")
    rows = rows_by_id(preset)
    if any(r.get("name") == WORKING_DIRECTORY_PLUGIN and r.get("disabled") is not True for r in rows.values()):
      return
    row_id = "cc-inherited-working-directory"
    if row_id in rows:
      raise GeneratorError("non-role preset has an unowned working-directory row collision")
    plugins.append({"id": row_id, "name": WORKING_DIRECTORY_PLUGIN})

  add_tool(standard)
  definitions = {p["id"]: copy.deepcopy(p) for p in inputs.other_presets}
  locations: dict[str, tuple[int, int | None]] = {}
  for i, entry in enumerate(data):
    if "insert" in entry and entry.get("id"):
      continue
    for j, row in enumerate(entry.get("insert", [entry])):
      row_id = row.get("id")
      if row.get("name") == PRESET_ROW_NAME and row_id != PRESET_ROW_ID:
        if row.get("config", {}).get("id") in {AGENT_ROW_PREFIX + r.name for r in inputs.roles}:
          continue
        definitions[row_id] = copy.deepcopy(row)
        locations[row_id] = (i, j if "insert" in entry else None)
      elif row_id in definitions:
        definitions[row_id].update(copy.deepcopy(row))
        locations[row_id] = (i, j if "insert" in entry else None)
  changed: dict[int, Any] = {}
  added: list[tuple[int | None, Any, Any]] = []
  for row_id, preset in definitions.items():
    before = canon(preset)
    add_tool(preset)
    if canon(preset) == before:
      continue
    if row_id not in locations:
      added.append((None, None, preset))
      continue
    i, j = locations[row_id]
    target = changed.setdefault(
      i, load(_MARKER_COMMENT.sub("", split_gap(chunks[i])[0], count=1), "non-role preset entry")[0]
    )
    if j is None:
      # Патч config заменяет весь config, поэтому сохраняем полный действующий список.
      target["config"] = preset["config"]
    else:
      target["insert"][j]["config"] = preset["config"]
  updates = [(i, data[i], row) for i, row in changed.items()]
  if enabled:
    added.append((None, None, {"id": WORKING_DIRECTORY_ROW, "disabled": True}))
  return [*updates, *added]


def is_agent_row(row: Any) -> bool:
  return isinstance(row, dict) and str(row.get("id", "")).startswith(AGENT_ROW_PREFIX)


def is_fork_row(row: Any) -> bool:
  return isinstance(row, dict) and row.get("id") == FORK_ROW_ID


def build_preset(
  shipped: Any, existing: Any, rows: list[dict[str, Any]], skills_dir: str
) -> tuple[Any, list[str]]:
  """The entry to write, with its warnings: the existing one if there is one (its edits stay), else the
  shipped row.

  Only the generator's part is refreshed: the cc-agent rows, the skills dir of skill-filesystem and
  `disabled` of the fork row, which would let the orchestrator fork itself past the delegation gate."""
  shipped_where = ("shipped standard preset", "the app layout changed")
  _, shipped_group = locate(shipped, *shipped_where)
  spawn = find_row(shipped_group["config"], "tool-subagent", SUBAGENT_PLUGIN, *shipped_where)
  if not isinstance(spawn.get("config"), dict) or spawn["config"].get("provider") != "spawn":
    raise GeneratorError("shipped standard preset: row 'tool-subagent' no longer uses spawn")
  if existing is None:
    preset, where = copy.deepcopy(shipped), shipped_where
  else:
    where = (f"existing {PRESET_ROW_ID} entry", "restore the row or delete the entry")
    preset = copy.deepcopy(existing)
  skills, group = locate(preset, *where)
  # Конфиг строки skill-filesystem не заменяем, а дополняем: чужие ключи и каталоги остаются.
  config = skills.setdefault("config", {})
  if not isinstance(config, dict) or not isinstance(config.get("customSkillDirs", []), list):
    raise GeneratorError(f"{where[0]}: row 'skill-filesystem' has an unexpected config")
  dirs = config.setdefault("customSkillDirs", [])
  if skills_dir not in dirs:
    dirs.append(skills_dir)
  children = group["config"]
  for i in reversed(range(len(children))):
    if is_agent_row(children[i]):
      del children[i]
  children.extend(rows)
  fork = next((c for c in children if is_fork_row(c)), None)
  if fork is None:  # строки нет в группе: не выдумываем её
    return preset, [
      f"{PRESET_ROW_ID}: row '{FORK_ROW_ID}' is missing from the delegation group; "
      "not added, so it could not be disabled"
    ]
  if "disabled" in fork:
    fork["disabled"] = True
  else:
    fork.insert(2, "disabled", True)  # как в поставляемых строках: после id и name
  return preset, []


def owned_rows(preset: Any) -> dict[str, str]:
  """Canonical form of the preset rows this tool writes, by row id."""
  config = preset.get("config") if isinstance(preset, dict) else None
  plugins = config.get("plugins") if isinstance(config, dict) else None
  out: dict[str, str] = {}
  for row in plugins if isinstance(plugins, list) else []:
    if not isinstance(row, dict):
      continue
    if row.get("id") == "skill-filesystem":
      out["skill-filesystem"] = canon(row)
    children = row.get("config") if row.get("id") == "delegation" else None
    for child in children if isinstance(children, list) else []:
      if is_agent_row(child) or is_fork_row(child):
        out[child["id"]] = canon(child)
  return out


def rows_by_id(preset: Any) -> dict[str, Any]:
  """Every row of the preset tree by id, the children of groups included."""
  found: dict[str, Any] = {}

  def walk(rows: Any) -> None:
    for row in rows if isinstance(rows, list) else []:
      if isinstance(row, dict):
        found[str(row.get("id"))] = row
        if row.get("group"):
          walk(row.get("config"))

  config = preset.get("config") if isinstance(preset, dict) else None
  walk(config.get("plugins") if isinstance(config, dict) else None)
  return found


def own_fields(row: dict[str, Any]) -> str:
  """Canonical form of a row without its children: a group's `config` holds rows compared on their own.

  The fork row is taken without `disabled`: this tool sets that field itself."""
  skip = {"disabled"} if is_fork_row(row) else set()
  return canon({k: v for k, v in row.items() if k not in skip and not (row.get("group") and k == "config")})


def preset_warnings(existing: Any, shipped: Any) -> list[str]:
  """Where the existing preset entry departs from the shipped preset; the entry's rows are kept as they are."""
  mine, theirs = rows_by_id(existing), rows_by_id(shipped)
  warnings: list[str] = []
  for row_id in sorted(mine.keys() | theirs.keys()):
    if row_id in {"skill-filesystem", "cc-inherited-working-directory"} or row_id.startswith(AGENT_ROW_PREFIX):
      continue
    if row_id not in mine:
      warnings.append(f"{PRESET_ROW_ID}: shipped row '{row_id}' is missing from the existing entry; not added")
    elif row_id not in theirs:
      warnings.append(f"{PRESET_ROW_ID}: row '{row_id}' of the existing entry is not in the shipped preset; kept")
    elif own_fields(mine[row_id]) != own_fields(theirs[row_id]):
      warnings.append(f"{PRESET_ROW_ID}: row '{row_id}' differs from the shipped preset; kept as it is")
  return warnings


# Метка генератора на первой строке записи: перед разбором снимаем, render_entry ставит заново.
_MARKER_COMMENT = re.compile(rf"[ \t]*#[ \t]*{re.escape(MARKER)}[ \t]*$", re.M)


def status(old: str | None, new: str) -> str:
  return "add" if old is None else "unchanged" if old == new else "update"


