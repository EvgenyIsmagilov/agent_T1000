def split_entries(text: str) -> tuple[str, list[str], list[int]]:
  """Header, one chunk per root-level `- ` entry, and the first line of each chunk."""
  lines = text.splitlines(keepends=True)
  starts = [i for i, line in enumerate(lines) if re.match(r"-([ \t]|$)", line)]
  bounds = [*starts, len(lines)]
  header = "".join(lines[: starts[0]]) if starts else text
  chunks = ["".join(lines[a:b]) for a, b in zip(bounds, bounds[1:])]
  return header, chunks, starts


def split_gap(chunk: str) -> tuple[str, str]:
  """Entry body and its trailing blank / column-0 comment lines (kept verbatim)."""
  lines = chunk.splitlines(keepends=True)
  end = len(lines)
  while end > 1 and (not lines[end - 1].strip() or lines[end - 1].startswith("#")):
    end -= 1
  return "".join(lines[:end]), "".join(lines[end:])


def last_index(entries: Sequence[Any], row_id: str) -> int | None:
  found = [
    i for i, e in enumerate(entries)
    if isinstance(e, dict) and e.get("id") == row_id and "insert" not in e
  ]
  return found[-1] if found else None


def is_model_tool_plugin(name: str) -> bool:
  """Recognize DSH tool providers, keeping known host-only service entry points."""
  return name not in NON_MODEL_TOOL_PLUGINS and (
    name == MCP_PLUGIN or name.startswith(("@deepseek-ai/dsh-tool-", "@deepseek-ai/dsh-experimental-tool-"))
    or name.endswith("/tools")
  )


def effective_global_entries(patches: Sequence[Any], initial: Sequence[Any] = ()) -> list[Any]:
  """Resolve root/group insertions and whole-field overrides in DSH patch order."""
  tree = copy.deepcopy(list(initial))
  by_id: dict[str, Any] = {}

  def index(rows: Sequence[Any]) -> None:
    for row in rows:
      if not isinstance(row, dict):
        raise GeneratorError("global composition contains a non-mapping entry")
      if isinstance(row.get("id"), str):
        by_id[row["id"]] = row
      if row.get("group") is True:
        if not isinstance(row.get("config"), list):
          raise GeneratorError("global group has no child list; cannot verify tool inheritance")
        index(row["config"])

  index(tree)
  for patch in copy.deepcopy(list(patches)):
    if not isinstance(patch, dict):
      raise GeneratorError("global patch contains a non-mapping entry")
    row_id = patch.get("id")
    if row_id is not None and not isinstance(row_id, str):
      raise GeneratorError("global row has a non-string id; cannot verify tool inheritance")
    if "insert" in patch:
      inserted = patch["insert"]
      if not isinstance(inserted, list):
        raise GeneratorError("global insert has no child list; cannot verify tool inheritance")
      if row_id:
        target = by_id.get(row_id)
        if target is None or target.get("group") is not True:
          raise GeneratorError("cannot resolve global insert target; cannot verify tool inheritance")
        target.setdefault("config", []).extend(inserted)
      else:
        tree.extend(inserted)
      index(inserted)
      continue
    target = by_id.get(row_id)
    if target is None:
      # Отдельная именованная строка может ссылаться на внешний бандл: считаем её потенциально действующей.
      if isinstance(patch.get("name"), str):
        tree.append(patch)
        index([patch])
      elif patch.get("disabled") is False:
        raise GeneratorError("cannot resolve enabled global row; cannot verify tool inheritance")
      continue
    if patch.get("name") and patch["name"] != target.get("name"):
      continue  # DSH пропускает патч, если имя плагина не совпадает.
    target.update({k: v for k, v in patch.items() if k not in {"id", "name"}})
  return tree


def active_global_rows(entries: Sequence[Any], depth: int = 0) -> list[tuple[Any, int]]:
  """Walk active host groups; Agent Preset child lists belong to their own scopes."""
  found: list[tuple[Any, int]] = []
  for row in entries:
    if not isinstance(row, dict):
      raise GeneratorError("global composition contains a non-mapping entry")
    if row.get("disabled") is True:
      continue
    found.append((row, depth))
    if row.get("group") is True:
      if not isinstance(row.get("config"), list):
        raise GeneratorError("global group has no child list; cannot verify tool inheritance")
      found.extend(active_global_rows(row["config"], depth + 1))
  return found


def reject_global_tools(entries: Sequence[Any], *, allow_working_directory: bool = False) -> None:
  """Refuse inherited model tools; conditional enablement is potentially active."""
  for row, _ in active_global_rows(entries):
    name = row.get("name", "")
    if not isinstance(name, str):
      raise GeneratorError("global plugin has no name; cannot verify tool inheritance")
    if allow_working_directory and name == WORKING_DIRECTORY_PLUGIN:
      continue
    if name == MCP_PLUGIN:
      raise GeneratorError("global MCP tools would be inherited by every role; move the client into a non-role preset")
    if is_model_tool_plugin(name):
      raise GeneratorError("global model-facing tools would be inherited by every role; move them into a non-role preset")


def omit_mcp(roles: list[RoleLine]) -> tuple[list[RoleLine], list[str]]:
  """MCP clients expose whole servers; omit MCP instead of granting extra tools."""
  kept: list[RoleLine] = []
  warnings: list[str] = []
  for role in roles:
    gone = [t for t in role.tools if t.startswith("mcp__")]
    if not gone:
      kept.append(role)
      continue
    left = [t for t in role.tools if t not in gone]
    if not left:
      raise GeneratorError(f"{role.name}: no tools left after omitting MCP tools: {', '.join(gone)}")
    kept.append(replace(role, tools=left, omitted=tuple(gone)))
    warnings.append(
      f"{role.name}: omitted {', '.join(gone)}: MCP tools are not included in generated role presets"
    )
  return kept, warnings


def role_preset_index(entries: Sequence[Any], chunks: list[str], line: RoleLine) -> int | None:
  """Find only this tool's single-row insert; reject a user-owned collision."""
  row_id, preset_id = ROLE_PRESET_ROW_PREFIX + line.name, AGENT_ROW_PREFIX + line.name
  found: int | None = None

  def matches(row: Any) -> bool:
    if not isinstance(row, dict):
      return False
    config = row.get("config")
    return row.get("id") == row_id or (
      row.get("name") == PRESET_ROW_NAME and isinstance(config, dict) and config.get("id") == preset_id
    ) or any(matches(r) for r in row.get("insert", [])) or (
      row.get("group") is True and isinstance(config, list) and any(matches(r) for r in config)
    )

  for i, entry in enumerate(entries):
    if not matches(entry):
      continue
    inserted = entry.get("insert")
    owned = (
      set(entry) == {"insert"} and isinstance(inserted, list) and len(inserted) == 1
      and isinstance(inserted[0], dict) and inserted[0].get("id") == row_id
      and inserted[0].get("name") == PRESET_ROW_NAME
      and isinstance(inserted[0].get("config"), dict) and inserted[0]["config"].get("id") == preset_id
      and _MARKER_COMMENT.search(chunks[i].splitlines()[0]) is not None
    )
    if not owned or found is not None:
      raise GeneratorError(f"{row_id}: refusing to replace an unowned role preset or duplicate definition")
    found = i
  return found


