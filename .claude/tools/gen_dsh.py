def role_preset_entry(line: RoleLine, skills_dir: str) -> dict[str, Any]:
  """Register one role's exact capabilities without inheriting the parent's preset."""
  tools = set(line.tools)
  if ("grep" in tools) != ("glob" in tools):
    raise GeneratorError(f"{line.name}: grep and glob must be enabled together; the DSH plugin registers both")
  plugins: list[dict[str, Any]] = [
    {"id": "persona", "name": "@deepseek-ai/dsh-persona",
     "config": {"prefix": LiteralScalarString(persona_text(line))}},
    {"id": "agent-instructions", "name": "@deepseek-ai/dsh-agent-instructions",
     "config": {"maxBytes": 65536}},
  ]
  if tools & {"read", "write", "edit"}:
    plugins.append({
      "id": "tool-fs", "name": "@deepseek-ai/dsh-tool-fs",
      "config": {"read": "read" in tools, "readImage": False, "write": "write" in tools, "edit": "edit" in tools},
    })
  if "bash" in tools:
    plugins.append({"id": "tool-bash", "name": "@deepseek-ai/dsh-tool-bash"})
  if "grep" in tools:
    plugins.append({
      "id": "tool-fs-search", "name": "@deepseek-ai/dsh-tool-fs-search",
      "config": {"sampleOverCapGlobResults": False},
    })
  if "skill" in tools:
    plugins.extend([
      {"id": "skill-filesystem", "name": "@deepseek-ai/dsh-skill-filesystem",
       "config": {"customSkillDirs": [skills_dir]}},
      {"id": "tool-skill", "name": "@deepseek-ai/dsh-tool-skill"},
    ])
  if tools & {"web_search", "web_fetch"}:
    plugins.append({
      "id": "tool-web", "name": "@deepseek-ai/dsh-tool-web",
      "config": {"search": "web_search" in tools, "fetch": "web_fetch" in tools},
    })
  return {"insert": [{
    "id": ROLE_PRESET_ROW_PREFIX + line.name, "name": PRESET_ROW_NAME,
    "config": {"id": AGENT_ROW_PREFIX + line.name, "plugins": plugins},
  }]}


# --- YAML ------------------------------------------------------------------------------------

class _Representer(RoundTripRepresenter):
  pass


# Приложение пишет `null`, ruamel по умолчанию пустое значение.
_Representer.add_representer(
  type(None), lambda self, data: self.represent_scalar("tag:yaml.org,2002:null", "null")
)


def _yaml() -> YAML:
  yaml = YAML(typ="rt")
  yaml.Representer = _Representer
  yaml.preserve_quotes = True
  yaml.width = 4096  # не переносить длинные строки
  yaml.indent(mapping=2, sequence=4, offset=2)  # стиль записи самого приложения
  return yaml


def load(text: str, what: str) -> Any:
  try:
    return _yaml().load(text.replace("!!js", STAND_IN))
  except YAMLError as e:
    # Только класс ошибки и строка: problem/context у ruamel цитируют значения из файла
    # (DuplicateKeyError печатает оба значения ключа), а среди них бывают секреты.
    mark = getattr(e, "problem_mark", None)
    where = f" at line {mark.line + 1}" if mark is not None else ""
    raise GeneratorError(f"cannot parse {what}: {type(e).__name__}{where}") from None


def _plain(node: Any) -> Any:
  if isinstance(node, dict):
    return {str(k): _plain(v) for k, v in node.items()}
  if isinstance(node, list):
    return [_plain(v) for v in node]
  if isinstance(node, TaggedScalar):
    return ["tag", str(node.tag).replace(STAND_IN, "!!js"), _plain(node.value)]
  if isinstance(node, str):
    return str(node).replace(STAND_IN, "!!js")
  return node


def canon(node: Any) -> str:
  """Comparable form of a node: values and order, no comments or formatting."""
  return json.dumps(_plain(node), ensure_ascii=False, default=str)


def render_entry(entry: Any, marker: str | None = None) -> str:
  """Text of one root-sequence entry in the style the app writes (dash at column 0)."""
  buf = io.StringIO()
  _yaml().dump(entry, buf)  # корень отдельной записи = mapping; корень-список ruamel отступает
  lines = buf.getvalue().replace(STAND_IN, "!!js").splitlines()
  first = f"- {lines[0]}" + (f"  # {marker}" if marker else "")
  return "\n".join([first, *(f"  {l}" if l.strip() else l for l in lines[1:])]) + "\n"


