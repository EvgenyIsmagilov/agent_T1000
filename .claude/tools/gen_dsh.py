# Белый список: значения этих ключей (и скалярные элементы списков под ними) печатаются как есть,
# всё остальное скрыто. Секрет не пройдёт через форму, которую никто не предусмотрел:
# `args: [--api-key, X]`, `url: https://u:X@h/?key=X`, `- {apiKey: X}`, `credential: X`, комментарий.
SAFE_KEYS = frozenset({
  "id", "name", "provider", "model", "displayName", "api", "apiKeyEnv", "toolName", "contextWindow",
  "maxTokens", "reasoningEffort", "reasoningEfforts", "input", "order", "backgroundMode", "group",
  "disabled", "customSkillDirs", "agentPreset", "read", "readImage", "write", "edit", "search", "fetch",
  "sampleOverCapGlobResults", "maxBytes",
})
HIDDEN = "<redacted>"
# Любой `#` между скалярами: парсер принимает комментарий и вплотную к `,` `[` `{` `]` `}`, без пробела.
_COMMENT = re.compile(r"#.*")


@dataclass
class _Node:
  """A mapping or a sequence on the way down to the scalar being looked at."""
  is_map: bool
  owner: str | None  # ключ, под которым висит коллекция: от него зависит, виден ли элемент списка
  key: str | None = None  # текущий ключ mapping
  want_key: bool = True  # mapping ждёт ключ, а не значение


def public_url(value: str) -> str:
  """scheme://host[:port] of a URL: userinfo, path, params, query and fragment may carry credentials."""
  try:
    parts = urlsplit(value)
  except ValueError:
    return HIDDEN
  if not parts.scheme or not parts.netloc:
    return HIDDEN
  return f"{parts.scheme}://{parts.netloc.rpartition('@')[2]}"


def hide_comment(m: re.Match[str]) -> str:
  return m[0] if m[0] == f"# {MARKER}" else f"# {HIDDEN}"


def redact(text: str) -> str:
  """Printable copy of a patch text: SAFE_KEYS values and the generator's marker stay, the rest is hidden.

  Works on the parser's scalar spans, not on lines, so flow collections, list items, URLs and
  block scalars are covered alike. Keys are names and are always shown."""
  source = text.replace("!!js", STAND_IN)
  try:
    events = list(_yaml().parse(source))
  except YAMLError:
    return f"{HIDDEN}: text does not parse\n"
  spans: list[tuple[int, int, str | None]] = []  # скаляр в source и что печатать вместо него (None = как есть)
  path: list[_Node] = []
  for ev in events:
    if isinstance(ev, (MappingEndEvent, SequenceEndEvent)):
      path.pop()
      continue
    if not isinstance(ev, (ScalarEvent, AliasEvent, MappingStartEvent, SequenceStartEvent)):
      continue
    parent = path[-1] if path else None
    is_key = parent is not None and parent.is_map and parent.want_key
    if parent is None:
      owner: str | None = None
    elif parent.is_map:
      if is_key:
        parent.key, owner = (ev.value if isinstance(ev, ScalarEvent) else ""), ""
      else:
        owner = parent.key
      parent.want_key = not is_key
    else:
      owner = parent.owner
    if isinstance(ev, (MappingStartEvent, SequenceStartEvent)):
      path.append(_Node(isinstance(ev, MappingStartEvent), owner))
    elif isinstance(ev, ScalarEvent) and ev.end_mark.index > ev.start_mark.index:
      start, end = ev.start_mark.index, ev.end_mark.index
      span = source[start:end]
      shown = None
      if not is_key and owner not in SAFE_KEYS:
        # блочный скаляр кончается переводом строки: сохраняем, чтобы не склеить строки
        shown = (public_url(ev.value) if owner == "baseURL" else HIDDEN) + span[len(span.rstrip("\n")):]
      elif ev.style in ("|", ">"):
        # показываемый блочный скаляр: комментарий в строке заголовка (`|  # …`) попал бы в span
        head, newline, rest = span.partition("\n")
        shown = _COMMENT.sub(hide_comment, head) + newline + rest
      spans.append((start, end, shown))
  out: list[str] = []
  pos = 0
  for start, end, shown in spans:  # между скалярами только синтаксис и комментарии
    out += [_COMMENT.sub(hide_comment, source[pos:start]), source[start:end] if shown is None else shown]
    pos = end
  out.append(_COMMENT.sub(hide_comment, source[pos:]))
  return "".join(out).replace(STAND_IN, "!!js")


def format_summary(plan: Plan, patch_file: Path, with_diff: bool) -> str:
  roles = [(
    r.name, f"{r.route}/{r.model}",
    "-" if r.effort is None else r.effort + (f" (requested {r.requested})" if r.effort != r.requested else ""),
    ", ".join(r.tools),
  ) for r in plan.result.roles]
  widths = [max(len(row[i]) for row in roles) for i in range(3)]
  out = [f"Patch file: {patch_file}", "", "Roles (name, route/model, effort, preset tools):"]
  out += ["  " + "  ".join(c.ljust(w) for c, w in zip(row, widths)) + "  " + row[3] for row in roles]
  if plan.warnings:
    out += ["", "Warnings:", *(f"  - {w}" for w in plan.warnings)]
  out += ["", "Owned entries:", *(f"  {label.ljust(34)} {state}" for label, state in plan.result.changes)]
  farm = plan.farm
  by_op = {op: [name for o, name in farm.ops if o == op] for op in ("add", "update", "remove")}
  counts = ", ".join(f"{op} {len(names)}" for op, names in by_op.items())
  out += ["", f"Skills farm {farm.path}: {counts}, unchanged {farm.unchanged}"]
  out += [f"  {op}: {', '.join(names)}" for op, names in by_op.items() if names]
  instructions = plan.instructions  # только путь, размер и состояние: в файле личная персона
  out += ["", f"Instructions file {instructions.path}: {instructions.state}, {len(instructions.new)} bytes"]
  if with_diff:
    diff = list(difflib.unified_diff(
      redact(plan.old_text).splitlines(keepends=True),
      redact(plan.result.text).splitlines(keepends=True),
      fromfile=str(patch_file), tofile=f"{patch_file} (generated)",
    ))
    if plan.result.text == plan.old_text:
      out += ["", "No changes."]
    elif diff:
      out += ["", "Diff (only allowlisted values shown, comments hidden):", *(l.rstrip("\n") for l in diff)]
    else:  # то, что изменилось, целиком в скрытом
      out += ["", "The texts differ only in hidden values or comments."]
  return "\n".join(out)


