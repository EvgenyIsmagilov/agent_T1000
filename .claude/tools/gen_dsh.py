def merge_providers(
  llm: Any, model_ids: Sequence[str]
) -> tuple[list[tuple[str, str]], list[str]]:
  """Add missing OpenRouter models and the dspark route to the llm-pi-ai entry, in place.

  An existing dspark route keeps every key this tool does not set; each one is reported by name."""
  config = llm.get("config")
  providers = config.get("providers") if isinstance(config, dict) else None
  route = providers.get("openrouter") if isinstance(providers, dict) else None
  if not isinstance(providers, dict) or not isinstance(route, dict):
    raise GeneratorError("row 'llm-pi-ai' has no providers.openrouter route; refusing to invent one")
  added: list[str] = []
  models = route.get("models")
  if isinstance(models, list):  # без списка маршрут и так отдаёт весь каталог
    known = {m.get("id") for m in models if isinstance(m, dict)}
    for model_id in model_ids:
      if model_id not in known:
        models.append({"id": model_id})
        added.append(model_id)
  warnings: list[str] = []
  old = providers.get("dspark")
  if isinstance(old, dict):
    stale = [key for key, value in DSPARK_ROUTE.items() if canon(old.get(key)) != canon(value)]
    for key in stale:
      old[key] = copy.deepcopy(DSPARK_ROUTE[key])
    dspark = "update" if stale else "unchanged"
    warnings = [
      f"llm-pi-ai dspark route: kept key '{key}', this tool does not set it" for key in old
      if key not in DSPARK_ROUTE
    ]
  else:
    providers["dspark"] = copy.deepcopy(DSPARK_ROUTE)
    dspark = "add" if old is None else "update"
  changes = [
    ("llm-pi-ai openrouter models", f"add {', '.join(added)}" if added else "unchanged"),
    ("llm-pi-ai dspark route", dspark),
  ]
  return changes, warnings


def hooks_index(entries: Sequence[Any]) -> int | None:
  """Index of the last root entry that is an `insert` of the hooks row.

  The app's own overrides of the row (`{id, disabled}`) are other entries and are not this tool's."""
  found = [
    i for i, e in enumerate(entries)
    if isinstance(e, dict) and isinstance(e.get("insert"), list)
    and any(isinstance(row, dict) and row.get("id") == HOOKS_ROW_ID for row in e["insert"])
  ]
  return found[-1] if found else None


def build_hooks_entry(existing: Any, config_path: str) -> Any:
  """The `insert` entry that mounts the hooks bridge: a new one, or `existing` with only `name` and
  `configPath` of the row set (every other key and row of it stays)."""
  if existing is None:
    return {"insert": [{"id": HOOKS_ROW_ID, "name": HOOKS_PLUGIN, "config": {"configPath": config_path}}]}
  entry = copy.deepcopy(existing)
  row = next(r for r in entry["insert"] if isinstance(r, dict) and r.get("id") == HOOKS_ROW_ID)
  if row.get("name") is None:
    row["name"] = HOOKS_PLUGIN
  elif row["name"] != HOOKS_PLUGIN:
    raise GeneratorError(f"row '{HOOKS_ROW_ID}' is not a {HOOKS_PLUGIN} row; refusing to take it over")
  config = row.setdefault("config", {})
  if not isinstance(config, dict):
    raise GeneratorError(f"row '{HOOKS_ROW_ID}' has an unexpected config")
  if config.get("configPath") != config_path:
    config["configPath"] = config_path
  return entry


def apply(old_text: str, inputs: Inputs) -> Result:
  """New text of the patch file; entries that need no change are not touched."""
  data = load(old_text, "patch file")
  if not isinstance(data, CommentedSeq):
    raise GeneratorError("patch file is not a YAML sequence")
  if any(not isinstance(entry, dict) for entry in data):
    raise GeneratorError("patch file contains a non-mapping entry")
  header, chunks, starts = split_entries(old_text)
  if starts != [data.lc.item(i)[0] for i in range(len(data))]:
    raise GeneratorError("patch file layout is not the block list of entries the app writes")
  llm_i = last_index(data, LLM_ROW_ID)
  if llm_i is None:
    raise GeneratorError(f"patch file has no '{LLM_ROW_ID}' row; refusing to invent one")

  def parse_owned(i: int, what: str) -> Any:
    """Entry `i` parsed on its own, without the generator's marker on its first line."""
    return load(_MARKER_COMMENT.sub("", split_gap(chunks[i])[0], count=1), what)[0]

  preset_i = last_index(data, PRESET_ROW_ID)
  existing: Any = None  # запись preset-standard из файла, разобранная отдельно, без метки генератора
  if preset_i is not None:
    existing = parse_owned(preset_i, f"row '{PRESET_ROW_ID}'")
  hooks_i = hooks_index(data)
  hooks_old: Any = None
  if hooks_i is not None:
    hooks_old = parse_owned(hooks_i, f"row '{HOOKS_ROW_ID}'")

  roles, omit_warnings = omit_mcp(inputs.roles)
  role_plans = []
  for role in roles:
    i = role_preset_index(data, chunks, role)
    old = parse_owned(i, "generated role preset") if i is not None else None
    role_plans.append((i, old, role_preset_entry(role, inputs.skills_dir)))
  reject_global_tools(effective_global_entries(data, inputs.global_entries), allow_working_directory=True)
  desired, preset_notes = build_preset(
    inputs.preset, existing, [agent_row(r) for r in roles], inputs.skills_dir
  )
  workdir_plans = preserve_working_directory(data, chunks, inputs, desired)
  result = Result(text="", roles=roles, warnings=[*omit_warnings, *preset_notes])
  have = {} if existing is None else owned_rows(existing)
  want = owned_rows(desired)
  result.changes.append((PRESET_ROW_ID, status(None if existing is None else canon(existing), canon(desired))))
  result.changes.extend((f"  {row_id}", status(have.get(row_id), now)) for row_id, now in want.items())
  result.changes.extend((f"  {row_id}", "remove") for row_id in have if row_id not in want)
  result.changes.extend(
    (new["insert"][0]["id"], status(None if old is None else canon(old), canon(new)))
    for _, old, new in role_plans
  )
  result.changes.extend(
    (new.get("id", "non-role preset insert"), "add" if old is None else "update")
    for _, old, new in workdir_plans
  )
  if existing is not None:
    result.warnings.extend(preset_warnings(existing, inputs.preset))

  body, gap = split_gap(chunks[llm_i])
  llm = load(body, f"row '{LLM_ROW_ID}'")[0]
  model_ids = list(dict.fromkeys(r.model for r in inputs.roles if r.route == "openrouter"))
  changes, merge_warnings = merge_providers(llm, model_ids)
  result.changes.extend(changes)
  result.warnings.extend(merge_warnings)
  if canon(llm) != canon(data[llm_i]):
    chunks[llm_i] = render_entry(llm) + gap

  hooks_new = build_hooks_entry(hooks_old, inputs.hooks_config)
  hooks_state = status(None if hooks_old is None else canon(hooks_old), canon(hooks_new))
  result.changes.append((HOOKS_ROW_ID, f"{hooks_state}  (configPath {inputs.hooks_config})"))

  def place(i: int | None, old: Any, new: Any, mark: bool = True) -> str:
    """Rewrite entry `i` when `new` differs from `old`; without an entry, return the text to append."""
    if i is None:
      return render_entry(new, MARKER)
    if canon(old) != canon(new):
      chunks[i] = render_entry(new, MARKER if mark else None) + split_gap(chunks[i])[1]
    return ""

  entries_to_place = [(preset_i, existing, desired), (hooks_i, hooks_old, hooks_new), *role_plans]
  tail = "".join(place(i, old, new) for i, old, new in entries_to_place)
  tail += "".join(place(i, old, new, mark=False) for i, old, new in workdir_plans)
  text = header + "".join(chunks)
  if tail:
    text += ("" if text.endswith("\n") else "\n") + tail
  result.text = text

  # Проверка записанного: перечитываем текст и сверяем с задуманным.
  new = load(text, "generated patch file")
  reject_global_tools(effective_global_entries(new, inputs.global_entries))
  expected = [canon(e) for e in data]
  expected[llm_i] = canon(llm)
  for i, _, entry in [*entries_to_place, *workdir_plans]:
    if i is None:
      expected.append(canon(entry))
    else:
      expected[i] = canon(entry)
  if [canon(e) for e in new] != expected:
    raise GeneratorError("generated text does not match the intended entries; nothing written")
  return result


def build_plan(paths: Paths) -> Plan:
  try:
    old_text = paths.patch_file.read_bytes().decode("utf-8")  # без перевода строк: бэкап должен быть точным
  except (OSError, UnicodeDecodeError) as e:
    raise GeneratorError(f"cannot read {paths.patch_file}: {reason(e)}") from None
  roles, warnings = build_roles(paths.agents_dir, load_catalog(paths.asar))
  other_presets, global_workdir, global_entries = load_other_presets(paths.asar)
  inputs = Inputs(
    load_shipped_preset(paths.asar), roles, str(paths.farm), str(paths.hooks_config),
    other_presets, global_workdir, global_entries
  )
  result = apply(old_text, inputs)
  if apply(result.text, inputs).text != result.text:
    raise GeneratorError("generator output is not stable (a second pass changes it); nothing written")
  warnings += result.warnings
  if not paths.hooks_config.is_file():  # мост без файла хуков стартует и не запускает ни одного хука
    warnings.append(
      f"{HOOKS_ROW_ID}: {paths.hooks_config} does not exist; the bridge logs a warning and runs no hooks"
    )
  farm, farm_warnings = plan_farm(paths.farm, paths.claude_skills, paths.local_skills)
  return Plan(
    old_text, result, [*warnings, *farm_warnings], farm, plan_instructions(paths.claude_md, paths.agents_md)
  )


# --- навыки: ссылки в farm -------------------------------------------------------------------

def skill_sources(claude_skills: Path, local_skills: Path) -> dict[str, Path]:
  """Skill dirs (a SKILL.md inside) by name; a dir of `local_skills` wins a name clash."""
  found: dict[str, Path] = {}
  for root, skip in ((claude_skills, SKIPPED_SKILLS), (local_skills, frozenset[str]())):
    try:
      dirs = sorted(root.iterdir())
    except OSError as e:
      raise GeneratorError(f"cannot read skills dir {root}: {reason(e)}") from None
    found.update({d.name: d for d in dirs if d.name not in skip and (d / "SKILL.md").is_file()})
  return found


def owned_target(link: Path, roots: tuple[Path, Path]) -> Path | None:
  """Where a link made by this tool points; None for anything else (a file, a directory, a link made by hand).

  This tool writes absolute links to a direct child of a source root, so only those count as its own."""
  if not link.is_symlink():
    return None
  target = Path(os.readlink(link))
  return target if target.is_absolute() and target.parent in roots else None


def plan_farm(farm: Path, claude_skills: Path, local_skills: Path) -> tuple[FarmPlan, list[str]]:
  """What to add, update and remove in the farm; an entry this tool did not make is only reported."""
  roots = (Path(os.path.abspath(claude_skills)), Path(os.path.abspath(local_skills)))
  wanted = skill_sources(*roots)
  try:
    present = {p.name: p for p in farm.iterdir()} if farm.exists() else {}
  except OSError as e:
    raise GeneratorError(f"cannot read skills farm {farm}: {reason(e)}") from None
  ops: list[tuple[str, str]] = []
  warnings: list[str] = []
  unchanged = 0
  for name in sorted(wanted.keys() | present.keys()):
    if name not in present:
      ops.append(("add", name))
      continue
    current = owned_target(present[name], roots)
    if current is None:
      warnings.append(
        f"skills farm: '{name}' is not a link this tool made; left as it is"
        + (", so that skill is not linked" if name in wanted else "")
      )
    elif name not in wanted:
      ops.append(("remove", name))
    elif current != wanted[name]:
      ops.append(("update", name))
    else:
      unchanged += 1
  return FarmPlan(farm, roots, wanted, ops, unchanged), warnings


def write_farm(plan: FarmPlan) -> None:
  """Apply the plan; a link is removed only while it still is one this tool made."""
  plan.path.mkdir(parents=True, exist_ok=True)
  for op, name in plan.ops:
    link = plan.path / name
    if op != "add":
      if owned_target(link, plan.roots) is None:
        raise GeneratorError(f"{link} changed after it was read; nothing more done, rerun the tool")
      link.unlink()
    if op != "remove":
      os.symlink(plan.wanted[name], link)


# --- AGENTS.md -------------------------------------------------------------------------------

_IMPORT = re.compile(r"@(\S+)")


def read_text(path: Path, what: str) -> str:
  try:
    return path.read_bytes().decode("utf-8")
  except (OSError, UnicodeDecodeError) as e:
    raise GeneratorError(f"cannot read {what} ({path}): {reason(e)}") from None


def expand_imports(claude_md: Path) -> str:
  """Text of the generated AGENTS.md: CLAUDE.md under a header, each line that is exactly `@<path>`
  replaced by that file's text.

  One level: an import inside an imported file stays as written. `~` is expanded, a relative path is taken
  from the dir of CLAUDE.md; a file that cannot be read is an error."""
  out = [INSTRUCTIONS_HEADER]
  for line in read_text(claude_md, "instructions source").splitlines(keepends=True):
    m = _IMPORT.fullmatch(line.rstrip())
    if m is None:
      out.append(line)
      continue
    text = read_text(claude_md.parent / os.path.expanduser(m[1]), f"import '{m[0]}'")
    out.append(text if text.endswith("\n") else text + "\n")
  return "".join(out)


def plan_instructions(claude_md: Path, agents_md: Path) -> InstructionsPlan:
  new = expand_imports(claude_md).encode("utf-8")
  try:
    old = agents_md.read_bytes() if os.path.lexists(agents_md) else None
    mode = None if old is None else stat.S_IMODE(agents_md.stat().st_mode)
  except OSError as e:
    raise GeneratorError(f"cannot read {agents_md}: {reason(e)}") from None
  return InstructionsPlan(agents_md, old, mode, new)


